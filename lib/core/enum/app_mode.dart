/// وضع استعمال التطبيق الحالي (الواجهة المعروضة)
/// ملاحظة: هذا غير دور الحساب (UserRole)، فالسائق المعتمد يملك الوضعين
enum AppMode { customer, driver }

// AppMode لتحديد الصفحات داخل التطبيق
/// حالة طلب الترقية إلى سائق (تُخزَّن في مستند المستخدم، وتغيّرها الإدارة فقط)
enum DriverStatus {
  /// لم يطلب الترقية
  none,

  /// أرسل الطلب وينتظر موافقة مسؤول النظام
  pending,

  /// وافقت الإدارة: يستطيع التبديل إلى وضع السائق
  approved,

  /// رفضت الإدارة الطلب
  rejected,
}

// تعريف جميع الصلاحيات الممكنة داخل التطبيق
enum Permission {

  // -------------------------------
  // صلاحيات الحساب الشخصي (User)
  // -------------------------------

  viewProfile,    // مشاهدة الملف الشخصي
  updateProfile,  // تعديل المعلومات الشخصية
  deleteAccount,  // حذف الحساب

  // -------------------------------
  // صلاحيات العميل (Customer)
  // -------------------------------

  createOrder,   // إنشاء طلب توصيل جديد
  cancelOrder,   // إلغاء طلب التوصيل الخاص به
  viewOwnOrders, // مشاهدة طلباته السابقة والحالية

  // -------------------------------
  // صلاحيات السائق (Driver)
  // -------------------------------

  viewAvailableOrders, // مشاهدة طلبات التوصيل المتاحة
  acceptOrder,         // قبول طلب توصيل
  rejectOrder,         // رفض طلب توصيل
  startDelivery,       // بدء عملية التوصيل
  completeDelivery,    // تأكيد إتمام عملية التوصيل
  viewAssignedOrders,  // مشاهدة الطلبات المسندة إليه

  // -------------------------------
  // صلاحيات إدارة السائق (Driver)
  // -------------------------------

  updateAvailability, // تغيير حالة التوفر (متاح / غير متاح)
  updateVehicleInfo,  // تعديل معلومات المركبة
  updateLocation,     // تحديث الموقع الجغرافي

  // -------------------------------
  // صلاحيات المدير (Admin)
  // -------------------------------

  manageUsers,   // إدارة حسابات المستخدمين
  manageDrivers, // إدارة حسابات السائقين
  approveDriver, // الموافقة على طلبات التسجيل كسائق
  suspendUser,   // إيقاف حساب مستخدم
  manageOrders,  // إدارة جميع طلبات التوصيل
  viewAllOrders, // مشاهدة جميع طلبات التوصيل
}